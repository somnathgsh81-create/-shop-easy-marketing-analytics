--------QUERY TO CATEGORIZE PRODUCTS ACCORDING TO PRICE-------------

SELECT 
PRODUCTID,
PRODUCTNAME,
PRICE,
CASE 
WHEN PRICE <50 THEN 'LOW'
WHEN PRICE BETWEEN 50 AND 200 THEN 'MEDIUM'
ELSE 'HIGH' END AS PRICE_CATEGORY

FROM DBO.PRODUCTS

--------------QUERY TO ENRICH CUSTOMER DATA WITH GEOGRAPHIC INFORMATION------------ 
SELECT 
C.CUSTOMERID,
C.CUSTOMERNAME,
C.EMAIL,
C.AGE,
G.COUNTRY,
G.CITY
FROM DBO.CUSTOMERS C
LEFT JOIN DBO.GEOGRAPHY G
ON C.GEOGRAPHYID = G.GEOGRAPHYID

----------------CLEAN THE REVIEW TEXT COLUMN--------------

SELECT 
    REVIEWID, 
    CUSTOMERID, 
    PRODUCTID,  
    REVIEWDATE,
    RATING,  
    REPLACE(REVIEWTEXT, '  ', ' ') AS REVIEWTEXT
FROM 
    DBO.CUSTOMER_REVIEWS
    ---------------------------CLEAN ENGAGEMENT TABLE-------------
    SELECT 
    ENGAGEMENTID,  
    CONTENTID,  
    CAMPAIGNID,  
    PRODUCTID,
    UPPER(REPLACE(CONTENTTYPE, 'SOCIALMEDIA', 'SOCIAL MEDIA')) AS CONTENTTYPE,  
    LEFT(VIEWSCLICKSCOMBINED, CHARINDEX('-', VIEWSCLICKSCOMBINED) - 1) AS VIEWS,  
    RIGHT(VIEWSCLICKSCOMBINED, LEN(VIEWSCLICKSCOMBINED) - CHARINDEX('-', VIEWSCLICKSCOMBINED)) AS CLICKS,  
    LIKES,  
    CONVERT(VARCHAR, TRY_CONVERT(DATETIME, ENGAGEMENTDATE), 104) AS ENGAGEMENTDATE
FROM 
    DBO.ENGAGEMENT_DATA  
WHERE 
    CONTENTTYPE != 'NEWSLETTER'

 -----CLEAN CUSTOMER JOURNEY------------------
 WITH DUPLICATERECORDS AS (
    SELECT 
        JOURNEYID,  
        CUSTOMERID,  
        PRODUCTID,  
        VISITDATE,  
        STAGE,  
        ACTION,  
        DURATION,  
        ROW_NUMBER() OVER (
            PARTITION BY CUSTOMERID, PRODUCTID, VISITDATE, STAGE, ACTION  
            ORDER BY JOURNEYID  
        ) AS ROW_NUM  
    FROM 
        DBO.CUSTOMER_JOURNEY  
)
    
SELECT *
FROM DUPLICATERECORDS
ORDER BY JOURNEYID;

SELECT 
    JOURNEYID,  
    CUSTOMERID,  
    PRODUCTID,  
    VISITDATE,  
    STAGE,  
    ACTION,  
    COALESCE(DURATION, AVG_DURATION) AS DURATION  
FROM 
    (
        SELECT 
            JOURNEYID,  
            CUSTOMERID,  
            PRODUCTID,  
            VISITDATE,  
            UPPER(STAGE) AS STAGE,  
            ACTION,  
            DURATION,  
            AVG(DURATION) OVER (PARTITION BY VISITDATE) AS AVG_DURATION,  
            ROW_NUMBER() OVER (
                PARTITION BY CUSTOMERID, PRODUCTID, VISITDATE, UPPER(STAGE), ACTION  
                ORDER BY JOURNEYID  
            ) AS ROW_NUM  
        FROM 
            DBO.CUSTOMER_JOURNEY  
    ) AS SUBQUERY  
WHERE 
    ROW_NUM = 1
